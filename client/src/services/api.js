import axios from "axios"
import { serverUrl } from "./config"
import { setUserData } from "../redux/userSlice"

export const getCurrentUser = async (dispatch) => {
    try {
        const result = await axios.get(serverUrl + "/api/user/currentuser" , {withCredentials:true})
        
        dispatch(setUserData(result.data))
    } catch (error) {
        if (error.response?.status !== 401) {
            console.error("Could not retrieve the current user:", error)
        }
        dispatch(setUserData(null))
    }
}

export const generateNotes = async (payload) => {
    try {
        const result = await axios.post(serverUrl+ "/api/notes/generate-notes" , payload , {withCredentials:true})
        console.log(result.data)
        return result.data

    } catch (error) {
        console.log(error)
        throw error
    }
}

export const downloadPdf = async (result) => {
    try {
        const response = await axios.post(serverUrl+ "/api/pdf/generate-pdf" , {result} , {
            responseType:"blob" , withCredentials:true
        })

        const blob = new Blob([response.data], {
      type: "application/pdf"
    });

    const url = window.URL.createObjectURL(blob);
    const link = document.createElement("a");
    link.href = url;
    link.download = "PrepPilot-study-notes.pdf";
    link.click();

    window.setTimeout(() => window.URL.revokeObjectURL(url), 1000);
    } catch (error) {
         throw new Error("PDF download failed", { cause: error });

    }
}